_TG_VIDEO_LIMIT = 49 * 1024 * 1024


def _plural_seconds(n: int) -> str:
    n_abs = abs(n) % 100
    if 11 <= n_abs <= 14:
        return "секунд"
    last = n_abs % 10
    if last == 1:
        return "секунда"
    if last in (2, 3, 4):
        return "секунды"
    return "секунд"


def format_bolt_seconds(seconds: float) -> str:
    n = max(0, int(round(seconds)))
    return f"Твоя цифра: {n} {_plural_seconds(n)}."


def resolve_video(key: str) -> Path | None:
    """Prefer a compressed file under Telegram's 50 MB limit."""
    stem = _VIDEO_STEMS.get(key, key)
    candidates = [
        VIDEOS_DIR / f"{stem}.compressed.mp4",
        VIDEOS_DIR / f"{stem}.mp4",
    ]
    existing = [p for p in candidates if p.exists() and p.stat().st_size > 1000]
    if not existing:
        return None
    small = [p for p in existing if p.stat().st_size <= _TG_VIDEO_LIMIT]
    return min(small or existing, key=lambda p: p.stat().st_size)


def resolve_lead_pdf(branch: str) -> Path | None:
    """Точный путь из LEAD_MAGNET или любой PDF в папке ветки."""
    meta = LEAD_MAGNET[branch]
    pdf = meta["pdf"]
    if pdf and pdf.exists() and pdf.stat().st_size > 1000:
        return pdf
    folder = CONTENT_DIR / branch
    if folder.is_dir():
        candidates = sorted(folder.glob("*.pdf"), key=lambda p: p.stat().st_mtime, reverse=True)
        for path in candidates:
            if path.stat().st_size > 1000:
                return path
    return None


